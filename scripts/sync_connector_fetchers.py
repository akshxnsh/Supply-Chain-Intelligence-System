"""Copy the plain fetchers next to each Fivetran connector.

`fivetran deploy` uploads only the connector's own folder, so a connector cannot import `src.fetchers`.
This script copies src/fetchers/http.py + the source's module into connectors/<name>/chainguard_fetchers/
(imports rewritten) so there is ONE source of truth. tests/test_connectors.py fails if copies drift.

    python -m scripts.sync_connector_fetchers
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "fetchers"
CONNECTORS = {  # connector folder -> fetcher module
    "gdelt": "gdelt",
    "gdacs": "gdacs",
    "portwatch": "portwatch",
    "federal_register": "federal_register",
    "open_meteo": "open_meteo",
    "ecb": "ecb",
}
HEADER = "# GENERATED by scripts/sync_connector_fetchers.py from src/fetchers/{name}.py - do not edit here.\n"


def render(module: str) -> dict[str, str]:
    """Return {filename: content} for one connector's chainguard_fetchers package."""
    files = {"__init__.py": ""}
    for name in ("http", module):
        text = (SRC / f"{name}.py").read_text(encoding="utf-8").replace("\r\n", "\n")
        text = text.replace("from src.fetchers.", "from chainguard_fetchers.")
        files[f"{name}.py"] = HEADER.format(name=name) + text
    return files


def main() -> None:
    for folder, module in CONNECTORS.items():
        target = ROOT / "connectors" / folder / "chainguard_fetchers"
        target.mkdir(parents=True, exist_ok=True)
        for fname, content in render(module).items():
            (target / fname).write_text(content, encoding="utf-8", newline="\n")
        print("synced", folder)


if __name__ == "__main__":
    main()
